#!/usr/bin/env python3
"""
Third-pass recovery: route paywalled/dead publisher links through open mirrors.

For every source still marked FAILED this script:
  1. asks the Semantic Scholar Graph API for the paper's metadata + openAccessPdf
  2. probes arXiv for a preprint of the same title
  3. archives whatever open full text it can find
  4. writes a stub Markdown record when only metadata is obtainable, so the
     citation is still on disk and the limitation is explicit rather than lost

Output: recovered PDFs/Markdown plus research/sources/UNRESOLVED_SOURCES.md.
"""

from __future__ import annotations

import csv
import json
import re
import subprocess
import time
import urllib.parse
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCES = ROOT / "sources"
LOG = SOURCES / "DOWNLOAD_LOG.csv"
OUT = SOURCES / "UNRESOLVED_SOURCES.md"
SEM = "http://api.semanticscholar.org/graph/v1/paper/search"
UA = "Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36"


def jfetch(url: str) -> dict | None:
    try:
        p = subprocess.run(["curl", "-sSL", "--max-time", "40", "-A", UA, url],
                           capture_output=True, text=True, timeout=55)
        return json.loads(p.stdout) if p.stdout.strip() else None
    except Exception:
        return None


def save_pdf(url: str, dest: Path) -> bool:
    tmp = dest.with_suffix(".part")
    try:
        p = subprocess.run(["curl", "-sSL", "--compressed", "--max-time", "90", "-A", UA,
                            "-o", str(tmp), "-w", "%{http_code}", url],
                           capture_output=True, text=True, timeout=110)
    except subprocess.TimeoutExpired:
        tmp.unlink(missing_ok=True)
        return False
    code = (p.stdout or "").strip()[-3:]
    if code.startswith(("2", "3")) and tmp.exists() and tmp.stat().st_size > 2000 \
            and tmp.read_bytes()[:5] == b"%PDF":
        dest.write_bytes(tmp.read_bytes())
        tmp.unlink(missing_ok=True)
        return True
    tmp.unlink(missing_ok=True)
    return False


def arxiv_preprint(title: str) -> tuple[str, str] | None:
    q = urllib.parse.quote(f'ti:"{title[:110]}"')
    data = jfetch(f"https://export.arxiv.org/api/query?search_query={q}&max_results=3")
    if not data or "entry" not in data:
        return None
    entries = [e for e in data["entry"] if "arxiv.org/abs" in str(e.get("id", ""))]
    if not entries:
        return None
    e = entries[0]
    aid = str(e["id"]).rsplit("/", 1)[-1].split("v")[0]
    return aid, f"https://arxiv.org/pdf/{aid}"


def write_stub(dest: Path, title: str, url: str, meta: dict | None) -> None:
    lines = [f"# {title or url}", "",
             "> **This source could not be retrieved in full.** Paywalled, dead, or",
             "> blocked at the time of archiving. The citation is preserved so the claim it",
             "> supports stays traceable, but the underlying text was not read and must be",
             "> obtained through institutional access before it is cited in the report.",
             "", f"- **URL:** {url}", ""]
    if meta:
        lines += ["## Open metadata (Semantic Scholar)", ""]
        for k in ("title", "year", "venue", "externalIds", "abstract"):
            if meta.get(k):
                val = meta[k]
                lines.append(f"- **{k}:** {val if k != 'abstract' else str(val)[:900]}")
        if meta.get("openAccessPdf"):
            lines.append(f"- **openAccessPdf:** `{json.dumps(meta['openAccessPdf'])}`")
    dest.with_suffix(".md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    rows = list(csv.DictReader(LOG.open(newline="", encoding="utf-8")))
    manifest = {e["url"]: e for e in json.loads((ROOT / "sources.json").read_text())}
    still = [r for r in rows if r["status"] != "OK"]

    print(f"attempting open-mirror recovery for {len(still)} sources ...", flush=True)
    md_lines = ["# Unresolved sources", "",
                "Sources that could not be archived in full. Each is cited somewhere in the",
                "research; none of them should be quoted in the final report unless the full",
                "text is first obtained. Regenerated by `research/recover_open.py`.", ""]

    for r in still:
        url = r["url"]
        entry = manifest.get(url, {})
        title = entry.get("title") or r.get("title", "")
        dest = SOURCES / r["category"] / r["id"]
        dest.parent.mkdir(parents=True, exist_ok=True)
        outcome, detail = "UNRESOLVED", ""

        # 1. Semantic Scholar search by title (works when the URL itself is paywalled)
        meta = None
        if title:
            data = jfetch(f"{SEM}?query={urllib.parse.quote(title)}&limit=1&fields=title,year,venue,externalIds,openAccessPdf,abstract")
            if data and data.get("data"):
                meta = data["data"][0]
                time.sleep(3.5)  # unauthenticated rate limit

        if meta:
            oa = (meta.get("openAccessPdf") or {}).get("url")
            if oa and save_pdf(oa, dest.with_suffix(".pdf")):
                outcome, detail = "RECOVERED", f"Semantic Scholar openAccessPdf ({oa})"
            else:
                found = arxiv_preprint(meta.get("title") or title)
                if found and save_pdf(found[1], dest.with_suffix(".pdf")):
                    outcome, detail = "RECOVERED", f"arXiv preprint {found[0]} matched by title"

        # 2. Derive a title from the URL if the manifest had none
        if outcome == "UNRESOLVED" and not title:
            slug = re.sub(r"[-_/]+", " ", url.rsplit("/", 1)[-1]).rsplit(".", 1)[0]
            title = f"(untitled) {slug}"[:120]

        if outcome != "RECOVERED":
            write_stub(dest, title, url, meta)
            detail = detail or "no open-access copy located"

        r.update(status="OK" if outcome == "RECOVERED" else "STUB",
                 file=str((dest.with_suffix(".pdf") if outcome == "RECOVERED" else dest.with_suffix(".md"))
                          .relative_to(ROOT)),
                 note=detail,
                 bytes=str((dest.with_suffix(".pdf") if outcome == "RECOVERED" else dest.with_suffix(".md"))).__len__() and
                       (dest.with_suffix(".pdf") if outcome == "RECOVERED" else dest.with_suffix(".md")).stat().st_size)
        print(f"  {outcome:<11} {r['id']:<30} {detail[:58]}", flush=True)
        md_lines.append(f"- **`{r['id']}`** ({r['category']}) — {title or url}")
        md_lines.append(f"  - {url}")
        md_lines.append(f"  - status: {outcome}; {detail}")
        time.sleep(1.0)

    with LOG.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["id", "category", "title", "cited_in", "url", "file", "bytes", "status", "note"])
        w.writeheader()
        w.writerows(rows)

    OUT.write_text("\n".join(md_lines) + "\n", encoding="utf-8")
    rec = sum(1 for r in still if r["status"] == "OK")
    print(f"\nrecovered {rec}, stubbed {len(still) - rec}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
