#!/usr/bin/env python3
"""
Second-pass recovery for sources that failed on the first fetch.

Many failures are publisher paywalls (403 from ScienceDirect / ACM DL / IEEE),
transient 429 rate-limits, or dead links. For each failure this script tries a
list of alternate routes (arXiv version, Semantic Scholar, DOI content
negotiation, a stripped URL, ...) and records which route worked.

Writes the recovered file under the original manifest id and updates
research/sources/DOWNLOAD_LOG.csv in place.
"""

from __future__ import annotations

import csv
import json
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCES = ROOT / "sources"
LOG = SOURCES / "DOWNLOAD_LOG.csv"
REPORT = SOURCES / "RETRY_REPORT.md"

UA = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) "
      "Chrome/126.0 Safari/537.36")
UA_PLAIN = "curl/8.5.0"
ACCEPT = "text/html,application/xhtml+xml,application/pdf;q=0.9,*/*;q=0.8"


def variants(url: str) -> list[tuple[str, str]]:
    """(label, url) alternate routes to try, most promising first."""
    out: list[tuple[str, str]] = []

    if "arxiv.org/abs/" in url:
        aid = url.rsplit("/", 1)[-1]
        base = aid.split("v")[0]
        out += [
            (f"arxiv html {base}v1", f"https://arxiv.org/html/{base}v1"),
            (f"arxiv html {base}", f"https://arxiv.org/html/{base}"),
            (f"arxiv pdf {base}", f"https://arxiv.org/pdf/{base}"),
        ]
    if "arxiv.org/pdf/" in url:
        base = url.rsplit("/", 1)[-1].removesuffix(".pdf").split("v")[0]
        out += [
            (f"arxiv html {base}v1", f"https://arxiv.org/html/{base}v1"),
            (f"arxiv abs {base}", f"https://arxiv.org/abs/{base}"),
        ]
    if "doi.org/" in url:
        out.append(("doi resolve", url))
    if "sciencedirect.com" in url:
        pii = url.rsplit("/", 1)[-1]
        out += [
            (f"semanticscholar pii {pii}", f"https://api.semanticscholar.org/graph/v1/paper/DOI:{pii}?fields=title,abstract,year,venue,externalIds,openAccessPdf"),
        ]
    out.append(("plain UA retry", url))
    return out


def try_url(url: str, dest_base: Path) -> tuple[Path, str] | tuple[None, str]:
    tmp = dest_base.with_suffix(".dl")
    for ua in (UA, UA_PLAIN):
        cmd = ["curl", "-sSL", "--compressed", "--max-time", "75",
               "-H", f"Accept: {ACCEPT}", "-A", ua,
               "-o", str(tmp), "-w", "%{http_code}", url]
        try:
            p = subprocess.run(cmd, capture_output=True, text=True, timeout=95)
        except subprocess.TimeoutExpired:
            continue
        code = (p.stdout or "").strip()[-3:]
        if not code.startswith(("2", "3")):
            last = f"http {code}"
            continue
        if not tmp.exists() or tmp.stat().st_size < 1200:
            last = "empty"
            continue
        blob = tmp.read_bytes()
        if blob[:5] == b"%PDF":
            out = dest_base.with_suffix(".pdf")
            out.write_bytes(blob)
            tmp.unlink(missing_ok=True)
            return out, "pdf"
        conv = subprocess.run(
            ["pandoc", "-f", "html", "-t", "gfm", "--wrap=none", str(tmp)],
            capture_output=True, text=True)
        text = (conv.stdout or blob.decode("utf-8", "ignore")).strip()
        if len(text) < 600:
            last = "js-rendered"
            continue
        out = dest_base.with_suffix(".md")
        out.write_text(text, encoding="utf-8")
        tmp.unlink(missing_ok=True)
        return out, "html->markdown"
    return None, locals().get("last", "unknown")


def main() -> int:
    rows = list(csv.DictReader(LOG.open(newline="", encoding="utf-8")))
    manifest = {e["url"]: e for e in json.loads((ROOT / "sources.json").read_text())}
    failed = [r for r in rows if r["status"] in ("FAILED", "MISSING", "STUB")]

    print(f"retrying {len(failed)} failures ...", flush=True)
    lines = ["# Retry report", "",
             "Second-pass recovery of sources that failed the first fetch.",
             "Regenerated by `research/retry_failed.py`.", "",
             "| id | category | first status | outcome | route used | file |",
             "|---|---|---|---|---|---|"]

    fixed = 0
    for r in failed:
        entry = manifest.get(r["url"], {})
        cat = r["category"]
        dest_base = SOURCES / cat / r["id"]
        dest_base.parent.mkdir(parents=True, exist_ok=True)

        outcome, route, chosen = "STILL-FAILING", "", ""
        for label, url in variants(r["url"]):
            path, how = try_url(url, dest_base)
            if path is not None:
                outcome, route, chosen = "RECOVERED", f"{label} ({how})", str(path.relative_to(ROOT))
                r.update(file=chosen, bytes=path.stat().st_size, status="OK",
                         note=f"recovered via {route}")
                fixed += 1
                break
            time.sleep(1.2)

        if outcome == "STILL-FAILING":
            r.setdefault("note", "")
            r["note"] = f"{r['note']} | all alternates failed: {route}".strip(" |")

        print(f"  {outcome:<13} {r['id']:<30} {route[:55]}", flush=True)
        lines.append(f"| {r['id']} | {cat} | {r.get('note','')[:40]} | {outcome} | {route} | {chosen} |")

    with LOG.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=["id", "category", "title", "cited_in", "url", "file", "bytes", "status", "note"])
        w.writeheader()
        w.writerows(rows)

    lines += ["", f"**Recovered: {fixed} / {len(failed)}**", "",
              "Recoveries and remaining failures are both recorded in "
              "`DOWNLOAD_LOG.csv`; re-run `python3 research/fetch_sources.py --retry-failed` "
              "to try again later."]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nrecovered {fixed}/{len(failed)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
